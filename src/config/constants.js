// 弾幕（少人数が大量に投稿していて、実際には盛り上がっていない番組）への補正。
//
// 🔴 **「弾幕かどうか」を判定して下げる方式にはしないこと。** 判定は必ず境界を持ち、
//    境界の両側で挙動が跳ぶ。ここでやるのは**全番組に同じ1本の式を通す**ことだけで、
//    弾幕でない番組は重みがほぼ 1 になるので式の上では何も起きない（doc/09 項目BE）。
//
//   r = コメント累計 / (来場者累計 + commentWeightViewerFloor)   … 1人あたり何コメントか
//   w = commentBaseWeight / (1 + (r / commentWeightHalfRatio) ^ commentWeightSharpness)
//   勢い = Δ来場者 + w × Δコメント
//
// 減衰の引き金は**Δコメントの大きさではなく r（1人あたり）**である。
// w は 0 に漸近するだけで**ゼロにはならない**（コメントが完全に無視されることはない）。
//
// 🔴 **2つの定数は役割が違う。取り違えないこと。**
//   - `commentBaseWeight` … 弾幕かどうかに関係なく**来場者を重く見る**ための係数。
//     全番組に一律に掛かるので、これだけでは弾幕と本物の差はつかない。
//   - `commentWeightHalfRatio` … **弾幕っぽさに応じて差をつける**ための係数。
//     こちらだけでは「来場より来場者を重く」にはならない。
//   利用者の要望が両方だったので2つある（2026-08-01）。
//
// ⚠️ 実測前の暫定値。実機で調整すること。効きが薄い/強すぎる時の動かし方:
//    - 弾幕がまだ高い → commentWeightHalfRatio を下げる（効き始めが早くなる）
//    - コメント全般をもっと軽く → commentBaseWeight を下げる
//    - 普通の番組まで沈んだ → 上と逆。Sharpness を上げると
//      「普通の範囲は触らず、極端なものだけ強く落とす」に寄る
export const commentWeightHalfRatio = 3;    // r がこの値で「形」の部分が半分になる
export const commentWeightSharpness = 1.5;  // 大きいほど「普通は素通し・極端だけ強く落とす」
// 来場者とコメントの基礎的な重み比（来場者 1 : コメント この値）。
// 🔴 **1.0 に戻すと「来場者を重く見る」という方針そのものが消える。**
// 2026-07-31 は 1:1 だったが、来場に重みを付けたいという利用者要望で 0.5 にした（2026-08-01）。
export const commentBaseWeight = 0.5;
// 若い番組・小さい番組は r が数件のコメントで暴れる（来場者3人・コメント15件で r=5 など）。
// 分母に下駄を履かせて、**データが少ないうちは自動的に「補正なし」側へ寄せる**（疑わしきは罰せず）。
